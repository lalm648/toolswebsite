export function getToolExperience(tool: ToolDefinition): ToolExperience {
  const experience = experienceBySlug[tool.slug];
  return {
    intent: experience?.intent ?? tool.description,
    input: experience?.input ?? categoryInputs[tool.category],
    controls: experience?.controls ?? "Adjust the available settings",
    preview: experience?.preview ?? "Review the result before saving",
    output: experience?.output ?? "Save or copy the finished result",
    capabilities: experience?.capabilities ?? [
      "Focused workflow",
      "Clear result",
      "No account",
    ],
  };
}
